export type ApiResult<T> = { ok: true; data: T } | { ok: false; error: string };

export type Hero = {
  hero_id: number;
  hero_name: string;
  hero_image: string;
  role: Role;
  ratings: Rating[] | null;
};

export type Role = {
  role_id: number;
  role_name: string;
  role_image: string;
};

export type Player = {
  player_id: number;
  gamertag: string;
  real_name: string | null;
  birthday: string | null;
  role: Role;
  player_image: string | null;
  native_region: string;
  current_team: Team | null;
  ratings: Rating[] | null;
};

export type Team = {
  team_id: number;
  team_name: string;
  team_image: string | null;
  competing_region: string;
  // Only present on /teams responses; nested players have no current_team
  players?: Player[] | null;
};

export type Region = "na" | "emea" | "japan" | "korea" | "pacific";

// Ids are generated by the database, so they are not part of create payloads
export type CreatePlayerRequest = {
  gamertag: string;
  real_name: string | null;
  birthday: string | null;
  player_role: number;
  native_region: Region;
  player_image: string | null;
  current_team: number | null;
};

export type CreateTeamRequest = {
  team_name: string;
  team_image: string | null;
  competing_region: Region;
};

// PUT replaces every editable field, so it takes the same body as POST
export type UpdateTeamRequest = CreateTeamRequest;

// The player PUT requires `ratings` (null is rejected) and can only update
// existing ratings by id, so the current ratings are always sent back
export type UpdatePlayerRating = {
  rating_id: number;
  ratings: string;
  hero: { hero_id: number };
};

export type UpdatePlayerRequest = CreatePlayerRequest & {
  ratings: UpdatePlayerRating[];
};

// POST responses only contain part of the created item
export type CreatedPlayer = { player_id: number; gamertag: string };
export type CreatedTeam = { team_id: number; team_name: string };

export type Rating = {
  rating_id: number;
  ratings: string;
  hero: Hero | null;
  player: Player | null;
  rating_user: string | null;
};
